CREATE TABLE CF_MUNICIPIO (
    ID_MUNICIPIO NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME         VARCHAR2(120) NOT NULL,
    UF           CHAR(2) NOT NULL,
    COD_IBGE     NUMBER(7) NOT NULL UNIQUE
);

CREATE TABLE CF_USUARIO (
    ID_USUARIO      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME            VARCHAR2(120) NOT NULL,
    EMAIL           VARCHAR2(150) NOT NULL UNIQUE,
    TELEFONE        VARCHAR2(20),
    SENHA_HASH      VARCHAR2(100) NOT NULL,
    PERFIL          VARCHAR2(10) DEFAULT 'CIDADAO' NOT NULL CHECK (PERFIL IN ('CIDADAO','ADMIN')),
    DT_NASCIMENTO   DATE,
    ID_MUNICIPIO    NUMBER(10) NOT NULL REFERENCES CF_MUNICIPIO(ID_MUNICIPIO),
    FONTE_GRANDE    CHAR(1) DEFAULT 'N' NOT NULL CHECK (FONTE_GRANDE IN ('S','N')),
    AUDIO_ATIVO     CHAR(1) DEFAULT 'S' NOT NULL CHECK (AUDIO_ATIVO IN ('S','N')),
    EXPO_PUSH_TOKEN VARCHAR2(200),
    ATIVO           CHAR(1) DEFAULT 'S' NOT NULL CHECK (ATIVO IN ('S','N')),
    DT_CADASTRO     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE CF_CONSENTIMENTO (
    ID_CONSENTIMENTO NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO       NUMBER(10) NOT NULL REFERENCES CF_USUARIO(ID_USUARIO) ON DELETE CASCADE,
    FINALIDADE       VARCHAR2(20) NOT NULL CHECK (FINALIDADE IN ('ANALISE_IA','ALERTA_GUARDIAO')),
    VERSAO_TERMO     VARCHAR2(10) NOT NULL,
    ACEITO           CHAR(1) NOT NULL CHECK (ACEITO IN ('S','N')),
    DT_REGISTRO      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE CF_VINCULO_GUARDIAO (
    ID_VINCULO   NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PROTEGIDO NUMBER(10) NOT NULL REFERENCES CF_USUARIO(ID_USUARIO),
    ID_GUARDIAO  NUMBER(10) NOT NULL REFERENCES CF_USUARIO(ID_USUARIO),
    PARENTESCO   VARCHAR2(30) NOT NULL,
    NIVEL_MINIMO VARCHAR2(10) DEFAULT 'GOLPE' NOT NULL CHECK (NIVEL_MINIMO IN ('SUSPEITO','GOLPE')),
    STATUS       VARCHAR2(10) DEFAULT 'PENDENTE' NOT NULL CHECK (STATUS IN ('PENDENTE','ATIVO','REVOGADO','RECUSADO')),
    DT_CRIACAO   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    DT_ACEITE    TIMESTAMP,
    CONSTRAINT CK_VINCULO_DISTINTOS CHECK (ID_PROTEGIDO <> ID_GUARDIAO),
    CONSTRAINT UQ_VINCULO_PAR UNIQUE (ID_PROTEGIDO, ID_GUARDIAO)
);

CREATE TABLE CF_CANAL_ORIGEM (
    ID_CANAL NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO   VARCHAR2(20) NOT NULL UNIQUE CHECK (CODIGO IN ('WHATSAPP','SMS','LIGACAO','EMAIL','CARTA','REDE_SOCIAL')),
    NOME     VARCHAR2(40) NOT NULL
);

CREATE TABLE CF_TIPO_GOLPE (
    ID_TIPO_GOLPE NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO        VARCHAR2(30) NOT NULL UNIQUE,
    NOME          VARCHAR2(80) NOT NULL,
    DESCRICAO     VARCHAR2(500),
    GRAVIDADE     NUMBER(1) NOT NULL CHECK (GRAVIDADE BETWEEN 1 AND 5),
    ORGAO_IMITADO VARCHAR2(60)
);

CREATE TABLE CF_VERIFICACAO (
    ID_VERIFICACAO     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO         NUMBER(10) NOT NULL REFERENCES CF_USUARIO(ID_USUARIO),
    ID_CANAL           NUMBER(10) REFERENCES CF_CANAL_ORIGEM(ID_CANAL),
    ID_TIPO_GOLPE      NUMBER(10) REFERENCES CF_TIPO_GOLPE(ID_TIPO_GOLPE),
    TIPO_ENTRADA       VARCHAR2(10) NOT NULL CHECK (TIPO_ENTRADA IN ('TEXTO','IMAGEM','LINK')),
    CONTEUDO_MASCARADO VARCHAR2(4000),
    HASH_CONTEUDO      VARCHAR2(64) NOT NULL,
    VEREDITO           VARCHAR2(15) CHECK (VEREDITO IN ('GOLPE','SUSPEITO','OFICIAL','DIREITO','INCONCLUSIVO')),
    SCORE_RISCO        NUMBER(3) CHECK (SCORE_RISCO BETWEEN 0 AND 100),
    EXPLICACAO         VARCHAR2(2000),
    ROTEIRO_AUDIO      VARCHAR2(1000),
    MENSAGEM_GUARDIAO  VARCHAR2(500),
    MODO               VARCHAR2(8) DEFAULT 'ONLINE' NOT NULL CHECK (MODO IN ('ONLINE','OFFLINE')),
    STATUS             VARCHAR2(12) DEFAULT 'PENDENTE' NOT NULL CHECK (STATUS IN ('PENDENTE','PROCESSADA','ERRO')),
    DT_CRIACAO         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    DT_PROCESSAMENTO   TIMESTAMP
);

CREATE INDEX IX_CF_VERIFICACAO_USR_DT ON CF_VERIFICACAO (ID_USUARIO, DT_CRIACAO);

CREATE TABLE CF_SINAL_DETECTADO (
    ID_SINAL       NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_VERIFICACAO NUMBER(10) NOT NULL REFERENCES CF_VERIFICACAO(ID_VERIFICACAO) ON DELETE CASCADE,
    TIPO_SINAL     VARCHAR2(25) NOT NULL CHECK (TIPO_SINAL IN (
        'URGENCIA','LINK_SUSPEITO','PEDIDO_SENHA','PEDIDO_SELFIE',
        'CHAVE_PIX','VALOR_DINHEIRO','REMETENTE_DESCONHECIDO','ORGAO_OFICIAL_CITADO'
    )),
    TRECHO         VARCHAR2(300),
    PESO           NUMBER(3,2) CHECK (PESO BETWEEN 0 AND 1)
);

CREATE TABLE CF_ALERTA_GUARDIAO (
    ID_ALERTA      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_VERIFICACAO NUMBER(10) NOT NULL REFERENCES CF_VERIFICACAO(ID_VERIFICACAO) ON DELETE CASCADE,
    ID_VINCULO     NUMBER(10) NOT NULL REFERENCES CF_VINCULO_GUARDIAO(ID_VINCULO),
    CANAL_ENVIO    VARCHAR2(10) DEFAULT 'PUSH' NOT NULL CHECK (CANAL_ENVIO IN ('PUSH','SMS')),
    STATUS         VARCHAR2(10) DEFAULT 'ENVIADO' NOT NULL CHECK (STATUS IN ('ENVIADO','LIDO','RESOLVIDO')),
    DT_ENVIO       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    DT_LEITURA     TIMESTAMP,
    CONSTRAINT UQ_ALERTA_VERIF_VINC UNIQUE (ID_VERIFICACAO, ID_VINCULO)
);

CREATE TABLE CF_FEEDBACK (
    ID_FEEDBACK    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_VERIFICACAO NUMBER(10) NOT NULL UNIQUE REFERENCES CF_VERIFICACAO(ID_VERIFICACAO) ON DELETE CASCADE,
    FOI_UTIL       CHAR(1) NOT NULL CHECK (FOI_UTIL IN ('S','N')),
    DESFECHO       VARCHAR2(15) CHECK (DESFECHO IN ('NAO_PAGUEI','PAGUEI','BLOQUEEI','DENUNCIEI','PEDI_BENEFICIO','OUTRO')),
    VALOR_EVITADO  NUMBER(12,2),
    DT_REGISTRO    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE CF_REGRA_OFFLINE (
    ID_REGRA   NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PADRAO     VARCHAR2(300) NOT NULL,
    TIPO_SINAL VARCHAR2(25) NOT NULL,
    PESO       NUMBER(3,2) NOT NULL,
    MENSAGEM   VARCHAR2(300) NOT NULL,
    VERSAO     NUMBER(5) NOT NULL,
    ATIVO      CHAR(1) DEFAULT 'S' NOT NULL CHECK (ATIVO IN ('S','N'))
);
